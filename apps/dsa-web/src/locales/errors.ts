export type ErrorTextKey = keyof typeof zh;
export const ERROR_TEXT = { zh, en, ko };

/** Resolves against the active UI language, so it is safe to call outside React. */
export const errorText = (key: ErrorTextKey, params?: UiTextParams): string =>
  formatUiText(ERROR_TEXT[getActiveUiLanguage()][key], params);
